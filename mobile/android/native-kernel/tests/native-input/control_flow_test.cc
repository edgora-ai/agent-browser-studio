struct Counters {
  std::uint64_t generation_serial = 0;
  std::uint64_t provider_serial = 0;
  int constructions = 0;
  int destructions = 0;
  int notifications = 0;
};

// std::weak_ptr tokens model lifetime observation only. They are NOT
// base::WeakPtr, FilteredGestureProvider, a touch-ACK queue or gesture events.
struct LifeToken {
  explicit LifeToken(std::uint64_t value) : identity(value) {}
  std::uint64_t identity;
};

struct ProviderStub {
  explicit ProviderStub(std::uint64_t value)
      : identity(value), lifetime(std::make_shared<LifeToken>(value)) {}
  const std::uint64_t identity;
  std::shared_ptr<const LifeToken> lifetime;
};

class RenderInputRouterSupportBase {
 public:
  RenderInputRouterSupportBase(bool child, input::RenderInputRouter* rir,
                               Counters& counters)
      : counters_(counters),
        generation_(++counters.generation_serial),
        child_(child),
        rir_(rir),
        lifetime_(std::make_shared<LifeToken>(generation_)),
        provider_(++counters.provider_serial) {
    ++counters_.constructions;
  }
  ~RenderInputRouterSupportBase() { ++counters_.destructions; }
  bool IsRenderInputRouterSupportChildFrame() const { return child_; }
  void NotifySiteIsMobileOptimized(bool value) {
    ++counters_.notifications;
    mobile_optimized_ = value;
  }
  Counters& counters_;
  const std::uint64_t generation_;
  const bool child_;
  input::RenderInputRouter* const rir_;
  std::shared_ptr<const LifeToken> lifetime_;
  ProviderStub provider_;
  bool mobile_optimized_ = false;
};

struct FrameSinkMetadata {
  std::unique_ptr<RenderInputRouterSupportBase> rir_support;
  bool is_mobile_optimized = false;
};

class FrameSinkManagerStub {
 public:
  FrameSinkId GetOldestParentByChildFrameId(const FrameSinkId& child) const {
    CHECK(!IsFrameSinkIdInRootSinkMap(child));
    // Only the first/oldest DIRECT parent, not an ancestor walk. A missing
    // entry models both absent mapping and an empty parent list; 0 is invalid.
    return parents.count(child) ? parents.at(child) : 0;
  }
  bool IsFrameSinkIdInRootSinkMap(const FrameSinkId& id) const {
    return roots.count(id) != 0;
  }
  std::map<FrameSinkId, FrameSinkId> parents;
  std::set<FrameSinkId> roots;
};

class InputManager {
 public:
  InputManager(FrameSinkManagerStub* manager, Counters* counters)
      : frame_sink_manager_(manager), counters_(counters) {}
  void RecreateRenderInputRouterSupport(const FrameSinkId& child_frame_sink_id,
                                       FrameSinkMetadata& frame_sink_metadata);
  std::unique_ptr<RenderInputRouterSupportBase> MakeRenderInputRouterSupport(
      input::RenderInputRouter* rir, const FrameSinkId& child) {
    // Stub factory mirrors only the upstream oldest-parent root/child choice.
    const auto parent = frame_sink_manager_->GetOldestParentByChildFrameId(child);
    const bool is_child = !frame_sink_manager_->IsFrameSinkIdInRootSinkMap(parent);
    return std::make_unique<RenderInputRouterSupportBase>(is_child, rir, *counters_);
  }
  FrameSinkManagerStub* frame_sink_manager_;
  Counters* counters_;
  std::map<FrameSinkId, std::unique_ptr<input::RenderInputRouter>> rir_map_;
  // Destroy supports before their RIRs and before fixture counters.
  std::map<FrameSinkId, FrameSinkMetadata> metadata_;
};

