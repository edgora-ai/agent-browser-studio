void RootChildRootRoundTripReconstructs() {
  Fixture f;
  f.Create(1, 100, true);
  const auto root = Take(f, 1);
  f.Detach(1);
  f.Attach(1, 200);
  const auto child = Take(f, 1);
  f.Detach(1);
  f.Attach(1, 100);
  const auto& current = f.Support(1);
  Require(!current.IsRenderInputRouterSupportChildFrame() &&
              current.generation_ != root.generation && current.generation_ != child.generation &&
              current.provider_.identity != root.provider_identity &&
              current.provider_.identity != child.provider_identity &&
              root.support_weak.expired() && child.support_weak.expired() &&
              root.provider_weak.expired() && child.provider_weak.expired(),
          "root -> child -> root must construct a genuinely new root generation");
  Require(current.rir_ == root.rir && current.rir_ == child.rir &&
              f.counters.constructions == 3 && f.counters.destructions == 2 &&
              f.counters.notifications == 3 && current.mobile_optimized_,
          "root round-trip reconstruction must notify and keep the same RIR");
}

