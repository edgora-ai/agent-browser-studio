struct Fixture {
  Counters counters;
  FrameSinkManagerStub topology;
  InputManager manager{&topology, &counters};

  void Create(FrameSinkId sink, FrameSinkId oldest_parent, bool root,
              bool mobile_optimized = true) {
    CHECK(manager.rir_map_.count(sink) == 0);
    if (root) topology.roots.insert(oldest_parent);
    topology.parents[sink] = oldest_parent;
    manager.rir_map_[sink] = std::make_unique<input::RenderInputRouter>(1000 + sink);
    auto& metadata = manager.metadata_[sink];
    metadata.is_mobile_optimized = mobile_optimized;
    manager.RecreateRenderInputRouterSupport(sink, metadata);
  }
  void Detach(FrameSinkId sink) { topology.parents.erase(sink); }
  void Attach(FrameSinkId sink, FrameSinkId oldest_parent) {
    topology.parents[sink] = oldest_parent;
    manager.RecreateRenderInputRouterSupport(sink, manager.metadata_.at(sink));
  }
  RenderInputRouterSupportBase& Support(FrameSinkId sink) const {
    return *manager.metadata_.at(sink).rir_support;
  }
};

struct Snapshot {
  std::uint64_t generation;
  std::uint64_t provider_identity;
  std::weak_ptr<const LifeToken> support_weak;
  std::weak_ptr<const LifeToken> provider_weak;
  input::RenderInputRouter* rir;
};

Snapshot Take(const Fixture& f, FrameSinkId sink) {
  const auto& support = f.Support(sink);
  return {support.generation_, support.provider_.identity, support.lifetime_,
          support.provider_.lifetime, f.manager.rir_map_.at(sink).get()};
}

void Require(bool condition, const char* message) {
  if (!condition) throw std::runtime_error(message);
}

void InitialNullRootAllocatesAndNotifies() {
  Fixture f;
  f.Create(1, 100, true);
  const auto snapshot = Take(f, 1);
  Require(!f.Support(1).IsRenderInputRouterSupportChildFrame(), "null root must allocate root support");
  Require(f.counters.constructions == 1 && f.counters.notifications == 1,
          "new root must allocate and notify exactly once");
  Require(f.Support(1).mobile_optimized_ && !snapshot.support_weak.expired() &&
              !snapshot.provider_weak.expired() && f.Support(1).rir_ == snapshot.rir,
          "new root lifetime/optimization/RIR must be initialized");
}

void InitialNullChildAllocatesAndNotifies() {
  Fixture f;
  // Setup checks stay inside this existing case, not extra regression cases.
  f.topology.roots.insert(100);
  f.topology.parents[200] = 100;
  Require(f.topology.GetOldestParentByChildFrameId(999) == 0,
          "no direct parent must return invalid, not the child itself");
  bool root_rejected = false;
  try {
    f.topology.GetOldestParentByChildFrameId(100);
  } catch (const std::runtime_error&) {
    root_rejected = true;
  }
  Require(root_rejected, "parent lookup must CHECK that child is not a root sink");
  f.Create(1, 200, false, false);
  Require(f.topology.GetOldestParentByChildFrameId(1) == 200,
          "lookup must return direct parent 200, never grandparent root 100");
  Require(f.Support(1).IsRenderInputRouterSupportChildFrame(), "null child must allocate child support");
  Require(f.counters.constructions == 1 && f.counters.notifications == 1 &&
              !f.Support(1).mobile_optimized_, "new child must notify false optimization value");
}

