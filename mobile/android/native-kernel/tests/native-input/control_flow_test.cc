void ThreeSinksThirtyRounds() {
  Fixture f;
  std::vector<Snapshot> original;
  for (int sink = 1; sink <= 3; ++sink) {
    f.Create(sink, 100, true, sink == 2);
    original.push_back(Take(f, sink));
  }
  bool remained_alive_while_detached = true;
  int cycles = 0;
  for (int round = 0; round < 30; ++round) {
    for (int sink = 1; sink <= 3; ++sink) {
      f.Detach(sink);
      remained_alive_while_detached &= !original.at(sink - 1).support_weak.expired();
      f.Attach(sink, 100);
      ++cycles;
    }
  }
  bool stable = remained_alive_while_detached;
  for (int sink = 1; sink <= 3; ++sink) {
    const auto& old = original.at(sink - 1);
    const auto& current = f.Support(sink);
    stable &= current.generation_ == old.generation &&
              current.provider_.identity == old.provider_identity &&
              !old.support_weak.expired() && !old.provider_weak.expired() &&
              current.rir_ == old.rir && f.manager.rir_map_.at(sink).get() == old.rir &&
              current.mobile_optimized_ == (sink == 2);
  }
  Require(cycles == 90 && stable && f.counters.constructions == 3 &&
              f.counters.destructions == 0 && f.counters.notifications == 3,
          "3 sinks x 30 rounds must retain generation/provider/weak lifetime/RIR");
}

void ChildToChildStillRecreates() {
  Fixture f;
  f.Create(1, 200, false, false);
  const auto old = Take(f, 1);
  f.manager.metadata_.at(1).is_mobile_optimized = true;
  f.Detach(1);
  f.Attach(1, 201);
  const auto& current = f.Support(1);
  Require(current.IsRenderInputRouterSupportChildFrame() &&
              current.generation_ != old.generation &&
              current.provider_.identity != old.provider_identity &&
              old.support_weak.expired() && old.provider_weak.expired(),
          "child -> child must preserve previous reconstruction behavior");
  Require(f.counters.constructions == 2 && f.counters.destructions == 1 &&
              f.counters.notifications == 2 && current.mobile_optimized_ &&
              current.rir_ == old.rir, "child recreation must notify and retain RIR");
}

