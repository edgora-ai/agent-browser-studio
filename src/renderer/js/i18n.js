  function detectLanguage() {
    var saved;
    try {
      saved = localStorage.getItem(STORAGE_KEY) || localStorage.getItem(LEGACY_STORAGE_KEY);
      if (saved && !localStorage.getItem(STORAGE_KEY)) localStorage.setItem(STORAGE_KEY, saved);
    } catch (e) { saved = null; }
    if (saved && dict[saved]) return saved;
    var nav = (typeof navigator !== "undefined" && navigator.language) ? navigator.language : "en-US";
    if (/^zh/i.test(nav)) return "zh-CN";
    return "en-US";
  }

  var current = detectLanguage();

  function t(key, fallback) {
    var bundle = dict[current] || dict[FALLBACK];
    if (bundle && bundle[key] !== undefined) return bundle[key];
    if (dict[FALLBACK] && dict[FALLBACK][key] !== undefined) return dict[FALLBACK][key];
    return fallback !== undefined ? fallback : key;
  }

  function getLanguage() { return current; }

  function setLanguage(lang) {
    if (!dict[lang]) return;
    current = lang;
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) { /* storage disabled */ }
    applyDom();
    // Push to main process so tray/menu strings stay in sync
    var api = window.agentBrowserAPI;
    if (api && api.app && api.app.setLanguage) {
      api.app.setLanguage(lang).catch(function () { /* main may not be ready */ });
    }
    document.dispatchEvent(new CustomEvent("agent-browser-language-change", { detail: { language: lang } }));
  }

  function nextLanguage() {
    var langs = Object.keys(dict);
    var idx = langs.indexOf(current);
    var next = langs[(idx + 1) % langs.length];
    setLanguage(next);
    return next;
  }

  // R128: replace an element's text without touching its element children —
  // used by [data-icon] hosts so a hydrated <svg> survives a language switch.
  function setLabelText(el, text) {
    var kept = [];
    for (var i = 0; i < el.childNodes.length; i++) {
      if (el.childNodes[i].nodeType === 1) kept.push(el.childNodes[i]);
    }
    el.textContent = "";
    for (var j = 0; j < kept.length; j++) el.appendChild(kept[j]);
    el.appendChild(document.createTextNode(text));
  }

  function applyDom() {
    document.documentElement.lang = current === "zh-CN" ? "zh-CN" : "en";
    var elTexts = document.querySelectorAll("[data-i18n]");
    for (var i = 0; i < elTexts.length; i++) {
      var el = elTexts[i];
      var key = el.getAttribute("data-i18n");
      if (!key) continue;
      var html = el.getAttribute("data-i18n-html") === "true";
      if (html) { el.innerHTML = t(key); continue; }
      // R128: an element that also hosts a hydrated icon keeps its <svg> —
      // write the label into the text node instead of replacing all children.
      if (el.getAttribute("data-icon")) setLabelText(el, t(key));
      else el.textContent = t(key);
    }
    var elPlaceholders = document.querySelectorAll("[data-i18n-placeholder]");
    for (var j = 0; j < elPlaceholders.length; j++) {
      var ep = elPlaceholders[j];
      var k = ep.getAttribute("data-i18n-placeholder");
      if (k) ep.setAttribute("placeholder", t(k));
    }
    var elTitles = document.querySelectorAll("[data-i18n-title]");
    for (var m = 0; m < elTitles.length; m++) {
      var et = elTitles[m];
      var kt = et.getAttribute("data-i18n-title");
      if (kt) et.setAttribute("title", t(kt));
    }
    // R160: <option> entries inside static <select> markup — their text is
    // the visible label, so it needs the same treatment as data-i18n.
    var elOptions = document.querySelectorAll("[data-i18n-option]");
    for (var q = 0; q < elOptions.length; q++) {
      var eo = elOptions[q];
      var ko = eo.getAttribute("data-i18n-option");
      if (ko) eo.textContent = t(ko);
    }
    // R128: icon-only buttons (close, send, overflow) carry no text node, so
    // their accessible name comes from aria-label — which must localize too.
    var elAria = document.querySelectorAll("[data-i18n-aria-label]");
    for (var n = 0; n < elAria.length; n++) {
      var ea = elAria[n];
      var ka = ea.getAttribute("data-i18n-aria-label");
      if (ka) ea.setAttribute("aria-label", t(ka));
    }
  }

  // Expose
  window.i18n = {
    t: t,
    get: getLanguage,
    set: setLanguage,
    next: nextLanguage,
    apply: applyDom,
  };

  document.addEventListener("DOMContentLoaded", function () {
    applyDom();
    // Push initial language to main process so tray menu localizes immediately
    var api = window.agentBrowserAPI;
    if (api && api.app && api.app.setLanguage) {
      api.app.setLanguage(current).catch(function () { /* ok */ });
    }
  });
